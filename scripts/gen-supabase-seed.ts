// Regenerates supabase/migrations/0003_settings_seed.sql and supabase/seed/sample_creators.sql
// from the app's constants and demo dataset:  npx tsx scripts/gen-supabase-seed.ts
import { writeFileSync, mkdirSync } from 'node:fs';
import { CATEGORIES, DEFAULT_PLANS, UPLOAD_TYPES } from '../src/domain/constants';
import { buildSeed } from '../src/data/seed';
import { byCollection, toRow } from '../src/server/remote/mapping';

const q = (v: unknown) => `$j$${JSON.stringify(v)}$j$`;

const settings = `-- Tandem — default platform settings (generated by scripts/gen-supabase-seed.ts).
-- Admins can change these later in the app (Admin → Platform settings).
insert into public.platform_settings (id, platform_fee_pct, default_agency_fee_pct, categories, plans, max_upload_mb, allowed_upload_types)
values (true, 8, 15,
  ${q(CATEGORIES.map((c) => ({ id: c.id, label: c.label, enabled: true })))}::jsonb,
  ${q(DEFAULT_PLANS)}::jsonb,
  50,
  ${q(UPLOAD_TYPES)}::jsonb)
on conflict (id) do nothing;
`;
writeFileSync('supabase/migrations/0003_settings_seed.sql', settings);

const seed = await buildSeed();
const spec = byCollection.get('creators')!;
const sample = seed.creators.filter((c) => c.sample && !c.userId).map((c) => toRow(spec, c as unknown as Record<string, unknown>));
mkdirSync('supabase/seed', { recursive: true });
writeFileSync('supabase/seed/sample_creators.sql', `-- OPTIONAL: ${sample.length} fictional sample creator profiles for trying discovery and matching.
-- Every profile is flagged sample = true and the app labels it "Sample". They have no
-- user accounts, so nobody can receive invitations through them. Remove with:
--   delete from public.creator_profiles where sample and user_id is null;
insert into public.creator_profiles
select * from jsonb_populate_recordset(null::public.creator_profiles, ${q(sample)}::jsonb)
on conflict (id) do nothing;
`);
console.log(`settings + ${sample.length} sample creators written`);
